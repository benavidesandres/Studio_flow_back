-- Cada módulo es dueño de las tablas con su prefijo. No hay claves foráneas entre módulos:
-- se referencian por id, para que la frontera se pueda cortar sin rehacer el modelo.

CREATE TABLE reparto_persona (
    id     BIGINT PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    rol    VARCHAR(20)  NOT NULL
);

-- Una fila por actor: es el objeto que se bloquea para serializar cambios en su agenda.
CREATE TABLE planificacion_agenda_actor (
    actor_id BIGINT PRIMARY KEY
);

CREATE TABLE planificacion_escena (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produccion_id BIGINT         NOT NULL,
    numero        VARCHAR(50)    NOT NULL,
    inicio        TIMESTAMP      NOT NULL,
    fin           TIMESTAMP      NOT NULL,
    locacion      VARCHAR(255)   NOT NULL,
    costo         NUMERIC(14, 2) NOT NULL
);

CREATE TABLE planificacion_escena_actor (
    escena_id BIGINT NOT NULL REFERENCES planificacion_escena (id),
    actor_id  BIGINT NOT NULL REFERENCES planificacion_agenda_actor (actor_id),
    PRIMARY KEY (escena_id, actor_id)
);

CREATE INDEX idx_planificacion_escena_actor ON planificacion_escena_actor (actor_id);

CREATE TABLE presupuesto_produccion (
    produccion_id BIGINT PRIMARY KEY,
    total         NUMERIC(14, 2) NOT NULL,
    comprometido  NUMERIC(14, 2) NOT NULL
);
